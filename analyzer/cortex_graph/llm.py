import hashlib
import json
import os
import re
import time
import unicodedata

DEFAULT_MODEL = 'claude-opus-5-5'
FALLBACK_BETA = 'server-side-fallback-2026-07-01'
MAX_TOKENS = 16000
MAX_CHARS = 60000
MIN_CHARS = 2000
MAX_MESSAGE_CHARS = 6000
POLL_SECONDS = 30
BATCH_TIMEOUT = 86400
MAX_RATE_RETRIES = 3
MAX_SERVER_RETRIES = 2
MAX_RETRY_AFTER = 120
CATEGORIES = ['identity', 'preference', 'goal', 'decision', 'event', 'relationship', 'skill', 'habit', 'project', 'fact', 'instruction']
REDACTED = '«redactado»'

SCHEMA = {
    'type': 'object',
    'properties': {
        'memories': {
            'type': 'array',
            'items': {
                'type': 'object',
                'properties': {
                    'text': {'type': 'string'},
                    'category': {'type': 'string', 'enum': CATEGORIES},
                    'subject': {'type': 'string'},
                    'attribute': {'type': 'string'},
                    'value': {'type': 'string'},
                    'when': {'type': 'string'},
                    'confidence': {'type': 'number'},
                    'msg': {'type': 'integer'},
                    'sensitive': {'type': 'boolean'},
                },
                'required': ['text', 'category', 'subject', 'attribute', 'value', 'when', 'confidence', 'msg', 'sensitive'],
                'additionalProperties': False,
            },
        },
    },
    'required': ['memories'],
    'additionalProperties': False,
}

SYSTEM_PROMPT = """You extract durable personal memories from a conversation history so that other assistants can know the owner of the history over time.

Input: a short header (conversation title, source, participants, owner names) followed by the messages of one conversation excerpt. Each message line starts with [index] timestamp author (role): text. The owner is the person whose history this is; role "user" normally means the owner.

Extract only durable facts that will still matter weeks or months later, about the owner or about people close to them. Valid categories:
- identity: name, age, location, nationality, languages, occupation, employer, education.
- preference: likes, dislikes, tastes, tools or styles they favor.
- goal: things they want to achieve or are working towards.
- decision: choices they made or commitments they took.
- event: dated happenings (trips, births, job changes, appointments, milestones).
- relationship: family, partners, friends, colleagues, clients, with the person's name and role.
- skill: abilities, expertise, stack, level.
- habit: routines and recurring behaviors.
- project: long-running projects, products, companies, studies.
- instruction: standing instructions the owner gives to assistants about how to answer or behave.
- fact: any other durable fact that does not fit the above.

Ignore: small talk and greetings; content generated by the assistant unless the owner explicitly confirms or adopts it; transient tasks and one-off questions (debugging a single error, translating a sentence, a recipe request); source code, logs and pasted documents; hypotheticals and examples; anything that is only true during this conversation.

Rules for every memory:
- text: one self-contained sentence in the same language as the conversation, written in the third person about the subject or, for the owner, without a pronoun-dependent context (for example "Vive en Medellín" or "Works as a data engineer at Acme"). Never invent details.
- subject: who the memory is about. Use "user" for the owner, otherwise the person's or thing's name as written.
- attribute: a short normalized English snake_case key for the kind of fact (for example location, employer, job_title, favorite_language, spouse, diet, current_goal, wake_time). Reuse the same key for the same kind of fact so that a newer value can supersede an older one.
- value: the normalized value only (for example "Medellín", "Acme", "vegetarian"), without extra words.
- when: the ISO date (YYYY-MM-DD) the fact refers to; if the fact is simply stated at the time of the message, use the date of the supporting message; use an empty string if unknown.
- msg: the index of the message that best supports the memory, exactly as shown in the brackets.
- confidence: a number from 0 to 1. Use at least 0.8 for explicit first-person statements, around 0.5 for inferences, and skip anything below 0.4.
- sensitive: true for health, finance, legal, sexual, political, religious or credential-like information, false otherwise. Never output passwords, keys, tokens or card numbers; text marked «redactado» has been removed on purpose.
- If the owner states that something changed, emit the new fact with the same subject and attribute.

Return an object with a single key "memories" holding the list. Return an empty list when nothing qualifies."""

FALLBACK_SECRETS = [
    re.compile(r'\bsk-[A-Za-z0-9_-]{16,}'),
    re.compile(r'\b(?:AKIA|ASIA)[0-9A-Z]{16}\b'),
    re.compile(r'\bgh[oprsu]_[A-Za-z0-9]{30,255}\b'),
    re.compile(r'\bxox[abposr]-[A-Za-z0-9-]{10,}'),
    re.compile(r'\beyJ[A-Za-z0-9_-]{8,}\.eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}'),
    re.compile(r'-----BEGIN [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----[\s\S]*?-----END [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----'),
    re.compile(r'(?i)\b(?:password|passwd|contraseña|clave|token|secret|api[_-]?key)\s*(?:es|is|=|:)\s*\S{4,}'),
    re.compile(r'\b(?:\d[ -]?){13,19}\b'),
]
FENCE_RE = re.compile(r'(```|~~~)[^\n]*\n[\s\S]*?(?:\1|\Z)')
TOOL_RE = re.compile(r'<(tool_use|tool_result|function_calls|antml:[a-z_]+)\b[\s\S]*?(?:</\1>|\Z)')
SPACE_RE = re.compile(r'\s+')
NORM_RE = re.compile(r'[^\w\s]', re.U)
DATE_RE = re.compile(r'^\d{4}-\d{2}-\d{2}')


def sdk():
    try:
        import anthropic
        return anthropic
    except Exception:
        return None


def available():
    if sdk() is None:
        return False, 'falta el paquete anthropic (instala cortex-graph[ai])'
    if os.environ.get('ANTHROPIC_API_KEY') or os.environ.get('ANTHROPIC_AUTH_TOKEN'):
        return True, 'credenciales en el entorno'
    config = os.environ.get('ANTHROPIC_CONFIG_DIR') or os.path.join(os.path.expanduser('~'), '.config', 'anthropic')
    if os.path.isdir(config):
        return True, 'perfil de anthropic'
    return False, 'sin credenciales: define ANTHROPIC_API_KEY'


def model_name(model=None):
    return model or os.environ.get('CORTEX_AI_MODEL') or DEFAULT_MODEL


def redact(text):
    try:
        from .context import redact as base
        text = base(text)[0]
    except Exception:
        pass
    for pattern in FALLBACK_SECRETS:
        text = pattern.sub(REDACTED, text)
    return text


def scrub(text):
    text = FENCE_RE.sub('[código omitido]', text or '')
    text = TOOL_RE.sub('[herramienta omitida]', text)
    text = redact(text)
    return SPACE_RE.sub(' ', text).strip()


def normalize(text):
    text = unicodedata.normalize('NFKD', str(text or '').casefold())
    text = ''.join(c for c in text if not unicodedata.combining(c))
    return SPACE_RE.sub(' ', NORM_RE.sub(' ', text)).strip()


def memory_id(text):
    return hashlib.sha1(normalize(text).encode('utf-8')).hexdigest()[:12]


def header(conv, owners):
    title = scrub(conv.get('title') or '')[:120] or '(sin título)'
    people = ', '.join(scrub(p)[:60] for p in (conv.get('participants') or []))
    names = ', '.join(sorted(scrub(o)[:60] for o in owners))
    return f'Conversation: {title}\nSource: {conv.get("source") or "generic"}\nParticipants: {people}\nOwner: {names}\n'


def message_line(m):
    text = scrub(m.get('text'))
    if not text:
        return None
    if len(text) > MAX_MESSAGE_CHARS:
        text = text[:MAX_MESSAGE_CHARS] + '…'
    when = (m.get('time') or '')[:19]
    author = scrub(m.get('author') or '')[:60]
    return f'[{m.get("i")}] {when} {author} ({m.get("role") or "other"}): {text}'


def make_chunks(conversations, owners, max_chars):
    max_chars = max(MIN_CHARS, int(max_chars or MAX_CHARS))
    chunks = []
    for ci, conv in enumerate(conversations):
        head = header(conv, owners)
        budget = max_chars - len(head)
        current, size = [], 0
        for m in conv.get('messages') or []:
            line = message_line(m)
            if line is None:
                continue
            if current and size + len(line) + 1 > budget:
                chunks.append({'conv': ci, 'head': head, 'lines': current})
                current, size = [], 0
            current.append((m.get('i'), line, (m.get('time') or '')[:10]))
            size += len(line) + 1
        if current:
            chunks.append({'conv': ci, 'head': head, 'lines': current})
    return chunks


def chunk_text(chunk):
    return chunk['head'] + '\nMessages:\n' + '\n'.join(line for _, line, _ in chunk['lines'])


def split_chunk(chunk):
    lines = chunk['lines']
    if len(lines) < 2:
        return None
    mid = len(lines) // 2
    return [dict(chunk, lines=lines[:mid]), dict(chunk, lines=lines[mid:])]


def request_params(chunk, model):
    return {
        'model': model,
        'max_tokens': MAX_TOKENS,
        'system': SYSTEM_PROMPT,
        'messages': [{'role': 'user', 'content': chunk_text(chunk)}],
        'output_config': {'effort': 'low', 'format': {'type': 'json_schema', 'schema': SCHEMA}},
        'cache_control': {'type': 'ephemeral'},
    }


def error_classes():
    mod = sdk()
    none = type('Unavailable', (Exception,), {})
    if mod is None:
        return none, none, none
    return mod.RateLimitError, mod.APIStatusError, mod.APIConnectionError


def retry_after(exc):
    try:
        value = int(float(exc.response.headers.get('retry-after', '30')))
    except Exception:
        value = 30
    return max(1, min(value, MAX_RETRY_AFTER))


def call_with_retry(fn, issues, label):
    rate, status, conn = error_classes()
    rate_left, server_left = MAX_RATE_RETRIES, MAX_SERVER_RETRIES
    while True:
        try:
            return fn()
        except rate as e:
            if rate_left <= 0:
                issues.append(f'{label}: límite de peticiones agotado')
                return None
            rate_left -= 1
            time.sleep(retry_after(e))
        except status as e:
            code = getattr(e, 'status_code', 0) or 0
            if code >= 500 and server_left > 0:
                server_left -= 1
                time.sleep(2)
                continue
            issues.append(f'{label}: error de la API ({code})')
            return None
        except conn:
            if server_left > 0:
                server_left -= 1
                time.sleep(2)
                continue
            issues.append(f'{label}: sin conexión con la API')
            return None


def first_text(message):
    for block in getattr(message, 'content', None) or []:
        if getattr(block, 'type', None) == 'text':
            return getattr(block, 'text', '') or ''
    return ''


def parse_message(message, chunk, conversation, source, issues, label):
    stop = getattr(message, 'stop_reason', None)
    if stop == 'refusal':
        issues.append(f'{label}: el modelo rechazó el fragmento')
        return [], False
    if stop == 'max_tokens':
        return [], True
    try:
        data = json.loads(first_text(message))
        items = data.get('memories') if isinstance(data, dict) else None
        if not isinstance(items, list):
            raise ValueError('forma inesperada')
    except Exception:
        issues.append(f'{label}: respuesta no válida')
        return [], False
    return build_records(items, chunk, conversation, source), False


def build_records(items, chunk, conversation, source):
    dates = {i: d for i, _, d in chunk['lines']}
    out = []
    for item in items:
        if not isinstance(item, dict):
            continue
        text = scrub(str(item.get('text') or ''))[:1000]
        if len(normalize(text)) < 3:
            continue
        category = item.get('category') if item.get('category') in CATEGORIES else 'fact'
        msg = item.get('msg')
        msg = msg if isinstance(msg, int) and not isinstance(msg, bool) and msg in dates else None
        when = str(item.get('when') or '')[:10]
        if not DATE_RE.match(when):
            when = dates.get(msg) or ''
        try:
            confidence = max(0.0, min(1.0, float(item.get('confidence'))))
        except (TypeError, ValueError):
            confidence = 0.5
        record = {
            'id': memory_id(text), 'text': text, 'doc': text[:500], 'category': category,
            'subject': scrub(str(item.get('subject') or 'user'))[:120] or 'user',
            'attribute': scrub(str(item.get('attribute') or ''))[:80],
            'value': scrub(str(item.get('value') or ''))[:300],
            'confidence': round(confidence, 3), 'origin': 'ai', 'source': source, 'msg': msg,
            'sensitive': bool(item.get('sensitive')),
        }
        if when:
            record['when'] = when
            record['valid_from'] = when
        out.append(record)
    return out


def merge(records):
    best = {}
    for r in records:
        old = best.get(r['id'])
        if old is None or r['confidence'] > old['confidence']:
            best[r['id']] = r
    return [best[k] for k in sorted(best)]


def run_chunk(client, chunk, model, conversations, issues, retry, label):
    conv = conversations[chunk['conv']]
    source = f'k:{conv["rel"]}#{conv["id"]}' if conv.get('rel') else None
    params = request_params(chunk, model)

    def send():
        return client.beta.messages.create(**params, betas=[FALLBACK_BETA], fallbacks='default')

    message = call_with_retry(send, issues, label)
    if message is None:
        return []
    return finish(client, message, chunk, model, conversations, source, issues, retry, label)


def finish(client, message, chunk, model, conversations, source, issues, retry, label):
    records, truncated = parse_message(message, chunk, conversations[chunk['conv']], source, issues, label)
    if not truncated:
        return records
    parts = split_chunk(chunk) if retry else None
    if not parts:
        issues.append(f'{label}: respuesta cortada por límite de tokens')
        return []
    out = []
    for n, part in enumerate(parts):
        out.extend(run_chunk(client, part, model, conversations, issues, False, f'{label}.{n}'))
    return out


def run_batch(client, chunks, model, conversations, issues, progress):
    requests = []
    for n, chunk in enumerate(chunks):
        params = request_params(chunk, model)
        requests.append({'custom_id': f'c{n}', 'params': params})
    created = call_with_retry(lambda: client.messages.batches.create(requests=requests), issues, 'lote')
    if created is None:
        return []
    deadline = time.monotonic() + BATCH_TIMEOUT
    while True:
        state = call_with_retry(lambda: client.messages.batches.retrieve(created.id), issues, 'lote')
        if state is None:
            return []
        if getattr(state, 'processing_status', None) == 'ended':
            break
        if time.monotonic() > deadline:
            issues.append('lote: tiempo de espera agotado')
            return []
        progress({'phase': 'batch', 'status': getattr(state, 'processing_status', None)})
        time.sleep(POLL_SECONDS)
    results = call_with_retry(lambda: {r.custom_id: r.result for r in client.messages.batches.results(created.id)}, issues, 'lote')
    if results is None:
        return []
    out = []
    for n, chunk in enumerate(chunks):
        label = f'fragmento {n + 1}'
        res = results.get(f'c{n}')
        kind = getattr(res, 'type', None)
        if kind != 'succeeded':
            issues.append(f'{label}: lote {kind or "sin resultado"}')
            continue
        conv = conversations[chunk['conv']]
        source = f'k:{conv["rel"]}#{conv["id"]}' if conv.get('rel') else None
        out.extend(finish(client, res.message, chunk, model, conversations, source, issues, True, label))
        progress({'phase': 'parse', 'done': n + 1, 'total': len(chunks)})
    return out


def extract_memories(conversations, owner_names=None, model=None, batch=False, client=None, on_progress=None, max_chars=MAX_CHARS, issues=None):
    issues = issues if issues is not None else []
    progress = on_progress or (lambda event: None)
    conversations = list(conversations or [])
    owners = set(owner_names or [])
    chunks = make_chunks(conversations, owners, max_chars)
    if not chunks:
        return []
    if client is None:
        mod = sdk()
        if mod is None:
            issues.append('falta el paquete anthropic')
            return []
        client = mod.Anthropic()
    model = model_name(model)
    if batch:
        records = run_batch(client, chunks, model, conversations, issues, progress)
    else:
        records = []
        for n, chunk in enumerate(chunks):
            records.extend(run_chunk(client, chunk, model, conversations, issues, True, f'fragmento {n + 1}'))
            progress({'phase': 'chunk', 'done': n + 1, 'total': len(chunks)})
    return merge(records)
