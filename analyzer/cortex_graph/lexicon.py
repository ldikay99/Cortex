def parse_groups(text):
    groups, current = [], None
    for raw in text.strip().splitlines():
        line = raw.strip()
        if not line:
            continue
        if raw.startswith(' ') and current is not None:
            current += ' ' + line
        else:
            if current is not None:
                groups.append(current)
            current = line
    if current is not None:
        groups.append(current)
    out = []
    for g in groups:
        heads, _, members = g.partition('|')
        out.append(([h.strip() for h in heads.split(',') if h.strip()], [m.strip() for m in members.split(',') if m.strip()]))
    return out


def parse_synonyms(text):
    return [[w.strip() for w in line.split(',') if w.strip()] for line in text.strip().splitlines()]
